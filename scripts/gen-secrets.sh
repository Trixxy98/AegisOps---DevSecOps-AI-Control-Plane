#!/usr/bin/env bash
# Generate a .env with random local secrets for Docker Compose.
# Usage: scripts/gen-secrets.sh [--output PATH] [--force | --upgrade]
# Refuses to overwrite an existing file unless --force is given; --upgrade appends only missing newer keys
# (APP_DB_PASSWORD, AI_CONTENT_*) to an existing file. Never prints secrets.
set -euo pipefail
cd "$(dirname "$0")/.."
output=".env"
force=false
upgrade=false
while [[ $# -gt 0 ]]; do
  case "$1" in
    --output) output="${2:?--output needs a path}"; shift 2 ;;
    --force) force=true; shift ;;
    --upgrade) upgrade=true; shift ;;
    -h|--help) sed -n '2,5p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $1" >&2; exit 2 ;;
  esac
done
if [[ "$force" == true && "$upgrade" == true ]]; then
  echo "--force and --upgrade cannot be combined." >&2
  exit 2
fi
command -v openssl >/dev/null || { echo "openssl is required." >&2; exit 1; }
rand() { openssl rand -base64 "$1" | tr -d '\n/+=' | cut -c1-"$2"; }

if [[ "$upgrade" == true ]]; then
  [[ -f "$output" ]] || { echo "$output does not exist; run without --upgrade to create it." >&2; exit 1; }
  added=()
  # Keys introduced after the first release; values are generated, never printed.
  if ! grep -q '^APP_DB_PASSWORD=' "$output"; then
    # A file without a trailing newline would glue the new key onto its last line.
    if [[ -s "$output" && "$(tail -c 1 "$output")" != "" ]]; then printf '\n' >> "$output"; fi
    {
      echo "# Restricted database role of the production api/worker (added by --upgrade; run migrate afterwards)."
      echo "APP_DB_PASSWORD=$(rand 48 32)"
    } >> "$output"
    added+=("APP_DB_PASSWORD")
  fi
  if ! grep -q '^AI_CONTENT_KEY_1=' "$output"; then
    if [[ -s "$output" && "$(tail -c 1 "$output")" != "" ]]; then printf '\n' >> "$output"; fi
    # An existing AI_CONTENT_ENABLED/CURRENT_KEY_ID line is kept; only missing lines are added.
    {
      echo "# Stored AI content encryption (docs/08; added by --upgrade; restart api afterwards)."
      grep -q '^AI_CONTENT_ENABLED=' "$output" || echo "AI_CONTENT_ENABLED=true"
      grep -q '^AI_CONTENT_CURRENT_KEY_ID=' "$output" || echo "AI_CONTENT_CURRENT_KEY_ID=key1"
      echo "AI_CONTENT_KEY_1=$(openssl rand -base64 32 | tr -d '\n')"
    } >> "$output"
    added+=("AI_CONTENT_KEY_1")
  fi
  if [[ ${#added[@]} -eq 0 ]]; then
    echo "$output already has every generated key; nothing changed."
  else
    echo "Added to $output: ${added[*]}. Run the migrate command (production), then restart api and worker."
  fi
  exit 0
fi

if [[ -e "$output" && "$force" != true ]]; then
  echo "$output already exists; re-run with --force to replace it, or --upgrade to add missing keys." >&2
  exit 1
fi
umask 077
tmp="$(mktemp "${output}.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by scripts/gen-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Do not commit."
  echo "POSTGRES_PASSWORD=$(rand 48 32)"
  # Restricted role of the production api/worker (SELECT/INSERT only on audit.*), created by the migrate command.
  echo "APP_DB_PASSWORD=$(rand 48 32)"
  echo "JWT_SIGNING_KEY=$(openssl rand -base64 48 | tr -d '\n')"
  echo "GRAFANA_ADMIN_PASSWORD=$(rand 48 24)"
  echo "WEBHOOK_SECRETS_ENABLED=false"
  echo "WEBHOOK_SECRETS_CURRENT_KEY_ID=key1"
  echo "WEBHOOK_SECRETS_KEY_1=$(openssl rand -base64 32 | tr -d '\n')"
  echo "WEBHOOK_SECRETS_KEY_2=$(openssl rand -base64 32 | tr -d '\n')"
  # Secret environment variables (docs/17 §5): stored AES-256-GCM encrypted with this key.
  echo "ENVIRONMENT_SECRETS_ENABLED=true"
  echo "ENVIRONMENT_SECRETS_CURRENT_KEY_ID=key1"
  echo "ENVIRONMENT_SECRETS_KEY_1=$(openssl rand -base64 32 | tr -d '\n')"
  # Stored AI content (AI policy StoreContent, docs/08): AES-256-GCM encrypted with this key.
  echo "AI_CONTENT_ENABLED=true"
  echo "AI_CONTENT_CURRENT_KEY_ID=key1"
  echo "AI_CONTENT_KEY_1=$(openssl rand -base64 32 | tr -d '\n')"
} > "$tmp"
chmod 600 "$tmp"
mv "$tmp" "$output"
trap - EXIT
echo "Wrote $output (mode 600). Note: an existing PostgreSQL volume keeps its old password."
